// tools/brand/gen.ts — the ONE producer of every brand-derived artifact.
//
// Discipline (01-01-PLAN.md:144, 02-PATTERNS.md §tools/brand/gen.ts):
//   - pure derivation functions returning plain objects/bytes;
//   - arrays sorted with a Buffer.compare byte comparator on UTF-8 bytes
//     (01-01-PLAN.md:140 — never localeCompare);
//   - one exported function serves both the generate and check paths, so the
//     two can never compute a different canonical form;
//   - validation (schema + semantic gates) happens BEFORE any output file is
//     opened — a garbage brand refuses (exit 2), it does not emit (T-02-01).
//
// Byte rules for every emitted artifact: sorted keys at every object level,
// byte-sorted entries, \n joins with a final \n, no BOM, no timestamps, and a
// header marking the file as generated / not hand-editable.
//
// CLI:
//   bun run tools/brand/gen.ts          regenerate from ./brand.json
//   bun run tools/brand/gen.ts --check  compare against committed files; never writes
//
// Exit codes: 0 clean; 1 drift (`--check`, or a hand-edit refusal in generate
// mode); 2 invalid brand (pre-write refusal, offending field named).

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export interface BrandFinding {
  field: string;
  message: string;
}

export interface BrandValidation {
  ok: boolean;
  findings: BrandFinding[];
}

interface BrandEntry {
  value: string;
  reason: string;
}

interface Brand {
  schema: string;
  version: number;
  product: { name: string; cli: string; display: string };
  npm: { scope: string; packages: { core: string } };
  python: { dist_prefix: string; module: string; entry_group: string };
  rust: { crate_prefix: string };
  home: {
    env: string;
    windows: string;
    posix: string;
    legacy: BrandEntry[];
    deviation_note?: string;
  };
  env: {
    prefix: string;
    legacy_prefixes: string[];
    exceptions?: string[];
  };
  db: { schema: string; legacy_schema: string };
  wire: { prefix: string; contract: string };
  tokens: { deny: BrandEntry[] };
}

type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

const BYTE_CMP = (a: string, b: string): number => Buffer.compare(Buffer.from(a, "utf8"), Buffer.from(b, "utf8"));

// Canonical constant names: dotted brand.json paths -> UPPER_SNAKE, one per language.
// The seven cross-language fields (product.name, product.cli, env.prefix, home.env,
// home.windows, home.posix, db.schema) share the same names in TS, Python, and Rust.
const SCALAR_FIELDS: [name: string, dotted: string][] = [
  ["DB_LEGACY_SCHEMA", "db.legacy_schema"],
  ["DB_SCHEMA", "db.schema"],
  ["ENV_LEGACY_PREFIXES", "env.legacy_prefixes"],
  ["ENV_PREFIX", "env.prefix"],
  ["HOME_ENV", "home.env"],
  ["HOME_POSIX", "home.posix"],
  ["HOME_WINDOWS", "home.windows"],
  ["NPM_PACKAGE_CORE", "npm.packages.core"],
  ["NPM_SCOPE", "npm.scope"],
  ["PRODUCT_CLI", "product.cli"],
  ["PRODUCT_DISPLAY", "product.display"],
  ["PRODUCT_NAME", "product.name"],
  ["PYTHON_DIST_PREFIX", "python.dist_prefix"],
  ["PYTHON_ENTRY_GROUP", "python.entry_group"],
  ["PYTHON_MODULE", "python.module"],
  ["RUST_CRATE_PREFIX", "rust.crate_prefix"],
  ["WIRE_CONTRACT", "wire.contract"],
  ["WIRE_PREFIX", "wire.prefix"],
];

function lookup(brand: Brand, dotted: string): string {
  let cur: unknown = brand;
  for (const part of dotted.split(".")) {
    if (cur === null || cur === undefined || typeof cur !== "object") throw new Error(`brand field missing: ${dotted}`);
    cur = (cur as Record<string, unknown>)[part];
  }
  if (typeof cur !== "string") throw new Error(`brand field not a string: ${dotted}`);
  return cur;
}

// The home.constants doc-comment, emitted in all three languages
// (AGENTS.md Migration-shims 'Config dir' row override — see brand.json home.deviation_note).
function homeNote(brand: Brand): string {
  return brand.home.deviation_note ?? "home values ship as generated from brand.json; no home constant is handwritten.";
}

const HEADER = "GENERATED by tools/brand/gen.ts from brand.json — DO NOT EDIT BY HAND.";
const RERUN = "Regenerate: just brand-gen. The drift gate (git diff --exit-code) fails on any hand edit.";
const SINGLE_SOURCE = "brand.json is the only hand-authored brand vocabulary; this file is its generated projection.";

function esc(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function sortedStrings(values: string[]): string[] {
  return [...values].sort(BYTE_CMP);
}

// One sorted name set for the per-language BRAND namespace objects: scalars and
// lists together, byte-sorted with the same comparator as every emitted array.
function allConstantNames(listNames: [string, string[]][]): string[] {
  const names = new Set<string>([...SCALAR_FIELDS.map(([n]) => n), ...listNames.map(([n]) => n)]);
  return [...names].sort(BYTE_CMP);
}

function tsLines(brand: Brand): string[] {
  const lines: string[] = [
    "// " + HEADER,
    "// " + RERUN,
    "// " + SINGLE_SOURCE,
    "",
  ];
  const listNames: [string, string[]][] = [
    ["ENV_LEGACY_PREFIXES", sortedStrings(brand.env.legacy_prefixes)],
    ["HOME_LEGACY", sortedStrings(brand.home.legacy.map((e) => e.value))],
    ["TOKENS_DENY", sortedStrings(brand.tokens.deny.map((e) => e.value))],
  ];
  for (const [name, dotted] of SCALAR_FIELDS) {
    if (name === "ENV_LEGACY_PREFIXES") continue; // emitted with the lists
    lines.push(`export const ${name} = "${esc(lookup(brand, dotted))}";`);
  }
  for (const [name, values] of listNames) {
    if (name === "HOME_LEGACY") lines.push(`// ${homeNote(brand)}`);
    if (name === "TOKENS_DENY") lines.push("");
    lines.push(`export const ${name} = [`);
    for (const v of values) lines.push(`  "${esc(v)}",`);
    lines.push(`] as const;`);
  }
  lines.push("");
  lines.push("export const BRAND = {");
  for (const name of allConstantNames(listNames)) lines.push(`  ${name},`);
  lines.push("} as const;");
  return lines;
}

function pyLines(brand: Brand): string[] {
  const lines: string[] = [
    "# " + HEADER,
    "# " + RERUN,
    "# " + SINGLE_SOURCE,
    "",
  ];
  const listNames: [string, string[]][] = [
    ["ENV_LEGACY_PREFIXES", sortedStrings(brand.env.legacy_prefixes)],
    ["HOME_LEGACY", sortedStrings(brand.home.legacy.map((e) => e.value))],
    ["TOKENS_DENY", sortedStrings(brand.tokens.deny.map((e) => e.value))],
  ];
  for (const [name, dotted] of SCALAR_FIELDS) {
    if (name === "ENV_LEGACY_PREFIXES") continue; // emitted with the lists
    lines.push(`${name} = "${esc(lookup(brand, dotted))}"`);
  }
  for (const [name, values] of listNames) {
    if (name === "HOME_LEGACY") lines.push(`# ${homeNote(brand)}`);
    lines.push(`${name} = (`);
    for (const v of values) lines.push(`    "${esc(v)}",`);
    lines.push(")");
  }
  lines.push("BRAND = {");
  for (const name of allConstantNames(listNames)) lines.push(`    "${name}": ${name},`);
  lines.push("}");
  return lines;
}

function rsLines(brand: Brand): string[] {
  const lines: string[] = [
    "// " + HEADER,
    "// " + RERUN,
    "// " + SINGLE_SOURCE,
    "",
  ];
  const listNames: [string, string[]][] = [
    ["ENV_LEGACY_PREFIXES", sortedStrings(brand.env.legacy_prefixes)],
    ["HOME_LEGACY", sortedStrings(brand.home.legacy.map((e) => e.value))],
    ["TOKENS_DENY", sortedStrings(brand.tokens.deny.map((e) => e.value))],
  ];
  for (const [name, dotted] of SCALAR_FIELDS) {
    if (name === "ENV_LEGACY_PREFIXES") continue; // emitted with the lists
    lines.push(`pub const ${name}: &str = "${esc(lookup(brand, dotted))}";`);
  }
  for (const [name, values] of listNames) {
    if (name === "HOME_LEGACY") lines.push(`/// ${homeNote(brand)}`);
    lines.push(`pub const ${name}: &[&str] = &[`);
    for (const v of values) lines.push(`    "${esc(v)}",`);
    lines.push("];");
  }
  return lines;
}

/**
 * Schema gate for brand.json. Walks the draft 2020-12 subset this schema uses
 * (required / type / pattern / minItems / minLength / const / enum) with
 * node:fs + JSON.parse only — no ajv (01-01-PLAN.md:214). Run BEFORE any
 * output file is opened (T-02-01); a finding names the offending field.
 */
export function validateBrand(brandJson: unknown, schemaJson: unknown): BrandValidation {
  const findings: BrandFinding[] = [];
  const schema = schemaJson as Record<string, JsonValue>;
  const brand = brandJson as Record<string, JsonValue>;

  const walk = (node: JsonValue, instance: unknown, at: string): void => {
    const n = node as Record<string, JsonValue>;
    const type = n.type as string | undefined;
    if (type && !typeMatches(type, instance)) {
      findings.push({ field: at || "<root>", message: `expected ${type}` });
      return;
    }
    if (n.const !== undefined && !Object.is(n.const, instance)) {
      findings.push({ field: at || "<root>", message: `must be ${JSON.stringify(n.const)}` });
    }
    if (Array.isArray(n.enum) && !n.enum.some((e) => Object.is(e, instance))) {
      findings.push({ field: at || "<root>", message: `must be one of ${n.enum.join("|")}` });
    }
    if (type === "object" || (typeof instance === "object" && instance !== null && !Array.isArray(instance))) {
      const obj = instance as Record<string, unknown>;
      for (const req of (n.required as string[]) ?? []) {
        if (!(req in obj)) findings.push({ field: at ? `${at}.${req}` : req, message: "required field is missing" });
      }
      const props = (n.properties as Record<string, JsonValue>) ?? {};
      for (const key of Object.keys(obj)) {
        if (key in props) walk(props[key], obj[key], at ? `${at}.${key}` : key);
      }
    }
    if (type === "string" && typeof instance === "string") {
      const p = n.pattern as string | undefined;
      if (p !== undefined && !new RegExp(p).test(instance)) {
        findings.push({ field: at || "<root>", message: `does not match ${p}` });
      }
      const minLen = n.minLength as number | undefined;
      if (minLen !== undefined && instance.length < minLen) {
        findings.push({ field: at || "<root>", message: `shorter than minLength ${minLen}` });
      }
    }
    if (type === "array" && Array.isArray(instance)) {
      const minItems = n.minItems as number | undefined;
      if (minItems !== undefined && instance.length < minItems) {
        findings.push({ field: at || "<root>", message: `fewer than minItems ${minItems}` });
      }
      const items = n.items as JsonValue | undefined;
      if (items) instance.forEach((el, i) => walk(items, el, `${at || "<root>"}[${i}]`));
    }
  };
  walk(schema, brand, "");
  if (findings.length === 0) {
    // Semantic gate (T-02-02): only after the schema is clean — the cast is
    // then justified by the schema (validated boundary).
    findings.push(...collisionFindings(brand as Brand));
  }
  return { ok: findings.length === 0, findings };
}

function typeMatches(type: string, v: unknown): boolean {
  switch (type) {
    case "object":
      return typeof v === "object" && v !== null && !Array.isArray(v);
    case "array":
      return Array.isArray(v);
    case "string":
      return typeof v === "string";
    case "integer":
      return typeof v === "number" && Number.isInteger(v);
    case "number":
      return typeof v === "number";
    case "boolean":
      return typeof v === "boolean";
    case "null":
      return v === null;
    default:
      return true;
  }
}

// Canonical legacy env names from the P-03 inventory (PITFALLS.md:126-138).
// The legacy-env table is RULES, not a 200-name enumeration: these names
// prove the prefix-swap transform; the ~200 HINDSIGHT_API_* names resolve at
// runtime through the prefix swap and are never enumerated (RESEARCH Pattern 4).
const CANONICAL_LEGACY_NAMES = ["HERMES_KANBAN_DB", "HINDSIGHT_API_DATABASE_SCHEMA", "OMP_HOME", "PI_NO_PTY"];

// Short-token family (RESEARCH Pattern 6): these deny tokens are restricted to
// identifier/string/env-name positions by the deny-gate (plan 02-08); a bare
// word-scan on them false-positives on api/pip/rapid and attribution prose.
const SHORT_TOKEN_FAMILIES = ["pi_", "omp", "pi-natives"];

/**
 * The legacy-env transform: full-prefix replacement, longest prefix first,
 * one legacy prefix maps to exactly one new prefix, never a double swap.
 */
export function transformName(name: string, legacyPrefixes: string[], newPrefix: string): string | null {
  const prefixes = [...legacyPrefixes].sort((a, b) => (b.length - a.length) || BYTE_CMP(a, b));
  for (const p of prefixes) {
    if (name.startsWith(p)) return newPrefix + name.slice(p.length);
  }
  return null;
}

// Collision/identity gate (Edge BRND-02/adjacency, T-02-02): two legacy names
// must never alias to one new name, and no rule may be a silent no-op.
function collisionFindings(brand: Brand): BrandFinding[] {
  const findings: BrandFinding[] = [];
  const names: string[] = [...CANONICAL_LEGACY_NAMES, ...(brand.env.exceptions ?? [])];
  for (const p of brand.env.legacy_prefixes) {
    if (p === brand.env.prefix) findings.push({ field: "env.legacy_prefixes", message: `COLLISION ${p}` });
  }
  const seen = new Map<string, string>();
  for (const name of sortedStrings(names)) {
    if (name.startsWith(brand.env.prefix)) {
      findings.push({ field: "env.exceptions", message: `COLLISION ${name}` });
      continue;
    }
    const to = transformName(name, brand.env.legacy_prefixes, brand.env.prefix);
    if (to === null) continue;
    const holder = seen.get(to);
    if (holder !== undefined && holder !== name) findings.push({ field: "env.exceptions", message: `COLLISION ${name}` });
    seen.set(to, name);
  }
  return findings;
}

function legacyEnvTsLines(brand: Brand): string[] {
  const newPrefix = brand.env.prefix;
  const lines: string[] = [
    "// " + HEADER,
    "// " + RERUN,
    "// Legacy env is a generated TRANSFORM, not a name list: full-prefix swap",
    "// (one legacy prefix maps to exactly one new prefix, never a double",
    "// swap). The canonical P-03 inventory names below are generated by",
    "// applying that transform; the ~200 HINDSIGHT_API_* names resolve at",
    "// runtime through it and are never enumerated here (RESEARCH Pattern 4).",
    "",
    "export const LEGACY_ENV_PREFIXES = [",
  ];
  for (const p of sortedStrings(brand.env.legacy_prefixes)) lines.push(`  "${esc(p)}",`);
  lines.push("] as const;");
  lines.push("// legacy prefix -> new prefix, then the canonical transformed names,");
  lines.push("// then the exception list (brand.json env.exceptions).");
  lines.push("export const LEGACY_ENV_MAP = {");
  for (const p of sortedStrings(brand.env.legacy_prefixes)) lines.push(`  ${p}: "${esc(newPrefix)}",`);
  for (const name of sortedStrings(CANONICAL_LEGACY_NAMES)) {
    const to = transformName(name, brand.env.legacy_prefixes, newPrefix);
    if (to !== null) lines.push(`  ${name}: "${esc(to)}",`);
  }
  lines.push("  exceptions: [");
  for (const e of sortedStrings(brand.env.exceptions ?? [])) lines.push(`    "${esc(e)}",`);
  lines.push("  ],");
  lines.push("};");
  lines.push("export function legacyToNew(name: string): string | null {");
  lines.push("  for (const p of LEGACY_ENV_PREFIXES) {");
  lines.push("    if (name.startsWith(p)) return (LEGACY_ENV_MAP as Record<string, string>)[p] + name.slice(p.length);");
  lines.push("  }");
  lines.push("  return null;");
  lines.push("}");
  return lines;
}

function legacyEnvPyLines(brand: Brand): string[] {
  const newPrefix = brand.env.prefix;
  const lines: string[] = [
    "# " + HEADER,
    "# " + RERUN,
    "# Legacy env is a generated TRANSFORM, not a name list: full-prefix swap",
    "# (one legacy prefix maps to exactly one new prefix, never a double",
    "# swap). The canonical P-03 inventory names below are generated by",
    "# applying that transform; the ~200 HINDSIGHT_API_* names resolve at",
    "# runtime through it and are never enumerated here (RESEARCH Pattern 4).",
    "",
    "LEGACY_ENV_PREFIXES = (",
  ];
  for (const p of sortedStrings(brand.env.legacy_prefixes)) lines.push(`    "${esc(p)}",`);
  lines.push(")");
  lines.push("LEGACY_ENV_MAP = {");
  for (const p of sortedStrings(brand.env.legacy_prefixes)) lines.push(`    "${esc(p)}": "${esc(newPrefix)}",`);
  for (const name of sortedStrings(CANONICAL_LEGACY_NAMES)) {
    const to = transformName(name, brand.env.legacy_prefixes, newPrefix);
    if (to !== null) lines.push(`    "${esc(name)}": "${esc(to)}",`);
  }
  lines.push(`    "exceptions": [${sortedStrings(brand.env.exceptions ?? []).map((e) => `"${esc(e)}"`).join(", ")}],`);
  lines.push("}");
  lines.push("def legacy_to_new(name: str):");
  lines.push("    for p in LEGACY_ENV_PREFIXES:");
  lines.push("        if name.startswith(p):");
  lines.push("            return LEGACY_ENV_MAP[p] + name[len(p):]");
  lines.push("    return None");
  return lines;
}

/**
 * Pure derivation of the deny-token config: one entry per tokens.deny token
 * with enumerated case variants (exact, title, upper) and a context —
 * "all" (prose + code + paths) for full product names, "identifier_string"
 * for the short-token family. Plan 02-08's deny-gate loads this table as its
 * behavioral contract; it is not scanned here.
 */
export function deriveDenyTokens(brand: Brand): Record<string, JsonValue> {
  const entries: Record<string, JsonValue>[] = [];
  for (const entry of sortedStrings(brand.tokens.deny.map((e) => e.value)).map((value) => {
    const found = brand.tokens.deny.find((e) => e.value === value);
    return found as { value: string; reason: string };
  })) {
    const title = entry.value.charAt(0).toUpperCase() + entry.value.slice(1);
    entries.push({
      case_variants: [entry.value, title, entry.value.toUpperCase()],
      context: SHORT_TOKEN_FAMILIES.includes(entry.value) ? "identifier_string" : "all",
      token: entry.value,
      reason: entry.reason,
    });
  }
  return { entries, schema: "halo/deny-tokens/v1", version: 1 };
}

/** Deterministic JSON text: keys byte-sorted at every level, 2-space indent. */
function stableStringify(value: JsonValue, indent = 0): string {
  const pad = "  ".repeat(indent);
  const child = "  ".repeat(indent + 1);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return "[\n" + value.map((v) => child + stableStringify(v, indent + 1)).join(",\n") + "\n" + pad + "]";
  }
  if (typeof value === "object" && value !== null) {
    const keys = Object.keys(value).sort(BYTE_CMP);
    if (keys.length === 0) return "{}";
    const obj = value as Record<string, JsonValue>;
    return "{\n" + keys.map((k) => `${child}${JSON.stringify(k)}: ${stableStringify(obj[k], indent + 1)}`).join(",\n") + "\n" + pad + "}";
  }
  return JSON.stringify(value);
}

/**
 * Pure derivation of the brand artifact set: brand.json -> Map<repo-relative
 * posix path, exact bytes>. Both the generate and check paths call this one
 * function, so they cannot diverge. Build ALL outputs in memory before
 * validateBrand passes and before anything is written (all-or-nothing).
 */
export function buildOutputs(brand: Brand): Map<string, Buffer> {
  const outputs = new Map<string, Buffer>();
  const files: [string, string[]][] = [
    ["runtime/shared_contracts/brand.gen.ts", tsLines(brand)],
    ["runtime/shared_contracts/halo_agent/brand_gen.py", pyLines(brand)],
    ["crates/halo-brand/src/brand_gen.rs", rsLines(brand)],
    ["runtime/shared_contracts/legacyEnv.gen.ts", legacyEnvTsLines(brand)],
    ["runtime/shared_contracts/halo_agent/legacy_env_gen.py", legacyEnvPyLines(brand)],
  ];
  for (const [rel, lines] of files) outputs.set(rel, Buffer.from(lines.join("\n") + "\n", "utf8"));
  const denyTokens = stableStringify(deriveDenyTokens(brand)) + "\n";
  outputs.set("tools/rebrand/deny-tokens.gen.json", Buffer.from(denyTokens, "utf8"));
  return outputs;
}

export function loadBrand(root: string): { brand: Brand; schema: unknown } {
  const brandRaw = readFileSync(path.join(root, "brand.json"), "utf8");
  const schemaRaw = readFileSync(path.join(root, "provenance", "schema", "brand.schema.json"), "utf8");
  const brand = JSON.parse(brandRaw) as Brand;
  const schema = JSON.parse(schemaRaw) as unknown;
  return { brand, schema };
}

export interface CliResult {
  exit: number;
  lines: string[];
}

// The committed (index) copy of a generated file: null when the path is not
// staged (a first write) or the root is not a git repo (scratch dirs).
// argv-array spawn, no shell (01-01-PLAN.md:121 discipline).
function indexBytes(root: string, rel: string): Buffer | null {
  const r = spawnSync("git", ["show", `:0:${rel}`], { cwd: root });
  if (r.status !== 0) return null;
  return r.stdout;
}

export function run(root: string, check: boolean): CliResult {
  let brand: Brand;
  let schema: unknown;
  try {
    ({ brand, schema } = loadBrand(root));
  } catch (err) {
    return { exit: 2, lines: [`BRAND INVALID ${err instanceof Error ? err.message : String(err)}`] };
  }
  const v = validateBrand(brand, schema);
  if (!v.ok) {
    return { exit: 2, lines: v.findings.map((f) => `BRAND INVALID ${f.field}: ${f.message}`) };
  }
  const outputs = buildOutputs(brand);
  if (check) {
    const drift: string[] = [];
    for (const [rel] of outputs) {
      let onDisk: Buffer;
      try {
        onDisk = readFileSync(path.join(root, rel));
      } catch {
        drift.push(`BRAND DRIFT ${rel}`);
        continue;
      }
      if (!onDisk.equals(outputs.get(rel)!)) drift.push(`BRAND DRIFT ${rel}`);
    }
    if (drift.length > 0) return { exit: 1, lines: drift };
    return { exit: 0, lines: ["BRAND OK unchanged"] };
  }
  // All-or-nothing write: classify every output first. A working-tree file whose
  // bytes differ from both the derivation and the committed (index) copy is a
  // hand edit — the generator refuses (BRAND DRIFT, exit 1, nothing written)
  // instead of silently rewriting past a reviewed diff (threat model: the
  // drift gate is the review mechanism). A file that matches the index but not
  // the derivation is a legitimate regeneration (brand.json changed) and is
  // written; a missing file is a first write.
  const toWrite: [string, Buffer][] = [];
  const drift: string[] = [];
  for (const [rel, bytes] of outputs) {
    const abs = path.join(root, rel);
    let onDisk: Buffer | null = null;
    try {
      onDisk = readFileSync(abs);
    } catch {
      /* absent */
    }
    if (onDisk === null) {
      toWrite.push([abs, bytes]);
      continue;
    }
    if (onDisk.equals(bytes)) continue;
    const committed = indexBytes(root, rel);
    if (committed !== null && onDisk.equals(committed)) toWrite.push([abs, bytes]);
    else drift.push(`BRAND DRIFT ${rel}`);
  }
  if (drift.length > 0) return { exit: 1, lines: drift };
  for (const [abs, bytes] of toWrite) {
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, bytes);
  }
  return {
    exit: 0,
    lines: [`BRAND OK generated files=${outputs.size}`],
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const r = run(process.cwd(), check);
  for (const line of r.lines) console.log(line);
  process.exit(r.exit);
}

// tools/brand/test/gen.test.ts — plan 02-01 Task 1 (tracer) coverage.
//
// Every negative case runs against a fresh scratch directory under the OS temp
// dir (01-08-PLAN.md:126 isolation) and never against the repo's committed
// outputs. Assertions name the finding token and the offending field — a
// non-zero exit alone is never a pass (01-08-PLAN.md:131 discipline).

import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { buildOutputs, loadBrand, transformName, validateBrand } from "../gen";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..", "..");
const GEN = path.join(REPO, "tools", "brand", "gen.ts");

// The seven cross-language fields (plan 02-01 Task 1 behavior): product.name,
// product.cli, env.prefix, home.env, home.windows, home.posix, db.schema.
const CROSS_LANG = ["PRODUCT_NAME", "PRODUCT_CLI", "ENV_PREFIX", "HOME_ENV", "HOME_WINDOWS", "HOME_POSIX", "DB_SCHEMA"] as const;

interface DenyEntry {
  value: string;
  reason: string;
}

// Narrowed access for the JSON round-trips this suite builds (in-process data
// the compiler lost track of): guard first, then a single named cast.
function denyOf(brand: Record<string, unknown>): DenyEntry[] {
  const tokens = brand.tokens;
  if (typeof tokens !== "object" || tokens === null) throw new Error("tokens missing");
  const deny = (tokens as Record<string, unknown>).deny;
  if (!Array.isArray(deny)) throw new Error("tokens.deny not an array");
  return deny as DenyEntry[];
}

function freshScratch(): string {
  return mkdtempSync(path.join(os.tmpdir(), "halo-brand-gen-"));
}

function makeRoot(brand: unknown, seedOutputs: boolean): string {
  const root = freshScratch();
  writeFileSync(path.join(root, "brand.json"), JSON.stringify(brand, null, 2) + "\n");
  mkdirSync(path.join(root, "provenance", "schema"), { recursive: true });
  writeFileSync(path.join(root, "provenance", "schema", "brand.schema.json"), readFileSync(path.join(REPO, "provenance", "schema", "brand.schema.json")));
  if (seedOutputs) {
    const r = runCli(root, []);
    if (r.status !== 0) throw new Error(`seed generation failed: ${r.stdout} ${r.stderr}`);
  }
  return root;
}

function runCli(root: string, args: string[]): { status: number | null; stdout: string; stderr: string } {
  const r = spawnSync(process.execPath, [GEN, ...args], { cwd: root, encoding: "utf8" });
  return { status: r.status, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
}

function readBrandJson(): Record<string, unknown> {
  return JSON.parse(readFileSync(path.join(REPO, "brand.json"), "utf8"));
}

function parseConst(raw: string, name: string, style: "ts" | "py" | "rs"): string {
  const m =
    style === "ts"
      ? raw.match(new RegExp(`export const ${name} = "((?:[^"\\\\]|\\\\.)*)";`))
      : style === "py"
        ? raw.match(new RegExp(`^${name} = "((?:[^"\\\\]|\\\\.)*)"$`, "m"))
        : raw.match(new RegExp(`pub const ${name}: &str = "((?:[^"\\\\]|\\\\.)*)";`));
  if (!m) throw new Error(`const ${name} not found in ${style} output`);
  return m[1];
}

describe("plan 02-01 Task 1 — brand vocabulary end to end", () => {
  test("the committed brand.json validates and regenerates idempotently (double run, fixed point)", () => {
    const { brand, schema } = loadBrand(REPO);
    const v = validateBrand(brand as never, schema);
    expect(v.ok).toBe(true);
    expect(v.findings).toEqual([]);

    const first = buildOutputs(brand as never);
    const second = buildOutputs(brand as never);
    for (const [rel, bytes] of first) expect(second.get(rel)?.equals(bytes)).toBe(true);

    // fixed point: re-parsing the brand document and re-deriving is byte-identical
    const roundTrip = JSON.parse(JSON.stringify(brand));
    const third = buildOutputs(roundTrip as never);
    for (const [rel, bytes] of first) expect(third.get(rel)?.equals(bytes)).toBe(true);

    const root = makeRoot(brand, false);
    const r1 = runCli(root, []);
    expect(r1.stdout.trim()).toBe("BRAND OK generated files=3");
    expect(r1.status).toBe(0);
    const r2 = runCli(root, []);
    expect(r2.stdout.trim()).toBe("BRAND OK unchanged");
    expect(r2.status).toBe(0);
    const rc = runCli(root, ["--check"]);
    expect(rc.status).toBe(0);
    expect(rc.stdout.trim()).toBe("BRAND OK unchanged");
  });

  test("each missing root key is refused with exit 2 naming that key, generated bytes untouched", () => {
    for (const key of ["schema", "version", "product", "npm", "python", "rust", "home", "env", "db", "wire", "tokens"]) {
      const brand = readBrandJson();
      const root = makeRoot(brand, true); // seed: valid outputs on disk first
      const seeded = buildOutputs(loadBrand(root).brand as never);
      delete (brand as Record<string, unknown>)[key];
      writeFileSync(path.join(root, "brand.json"), JSON.stringify(brand, null, 2) + "\n");
      const r = runCli(root, []);
      expect(r.status, `exit code for missing ${key}`).toBe(2);
      expect(r.stdout, `stdout for missing ${key}`).toContain(`BRAND INVALID ${key}`);
      for (const [rel, bytes] of seeded) {
        expect(readFileSync(path.join(root, ...rel.split("/"))).equals(bytes), `output ${rel} must be untouched`).toBe(true);
      }
    }
  });

  test("an empty tokens.deny is refused (Edge BRND-02/empty), naming the field", () => {
    const brand = readBrandJson();
    const root = makeRoot(brand, true);
    const seeded = buildOutputs(loadBrand(root).brand as never);
    const tokens = brand.tokens;
    if (typeof tokens !== "object" || tokens === null) throw new Error("tokens missing");
    (tokens as Record<string, unknown>).deny = [];
    writeFileSync(path.join(root, "brand.json"), JSON.stringify(brand, null, 2) + "\n");
    const r = runCli(root, []);
    expect(r.status).toBe(2);
    expect(r.stdout).toContain("BRAND INVALID tokens.deny");
    for (const [rel, bytes] of seeded) {
      expect(readFileSync(path.join(root, ...rel.split("/"))).equals(bytes)).toBe(true);
    }
  });

  test("a hand edit of a generated file is refused in generate mode (exit 1, BRAND DRIFT, edit preserved, no partial writes)", () => {
    const { brand } = loadBrand(REPO);
    const root = makeRoot(brand, true);
    const p = path.join(root, "runtime", "shared_contracts", "brand.gen.ts");
    const seeded = readFileSync(p);
    const bytes = readFileSync(p);
    writeFileSync(p, Buffer.concat([bytes, Buffer.from("edit\n")]));
    const other = path.join(root, "runtime", "shared_contracts", "halo_agent", "brand_gen.py");
    const otherBefore = readFileSync(other);
    const r = runCli(root, []);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain("BRAND DRIFT runtime/shared_contracts/brand.gen.ts");
    expect(readFileSync(p)).toEqual(Buffer.concat([seeded, Buffer.from("edit\n")]));
    expect(readFileSync(other).equals(otherBefore)).toBe(true);
  });

  test("byte stability: shuffled input arrays regenerate byte-identically; locale-vs-byte pair orders by bytes", () => {
    const { brand } = loadBrand(REPO);
    const baseline = buildOutputs(brand as never);

    const shuffled = JSON.parse(JSON.stringify(brand)) as Record<string, unknown>;
    const home = shuffled.home;
    if (typeof home !== "object" || home === null) throw new Error("home missing");
    const legacy = (home as Record<string, unknown>).legacy;
    if (!Array.isArray(legacy)) throw new Error("home.legacy not an array");
    legacy.reverse();
    denyOf(shuffled).reverse();
    const env = shuffled.env;
    if (typeof env !== "object" || env === null) throw new Error("env missing");
    const prefixes = (env as Record<string, unknown>).legacy_prefixes;
    if (!Array.isArray(prefixes)) throw new Error("env.legacy_prefixes not an array");
    prefixes.reverse();
    const reshuffled = buildOutputs(shuffled as never);
    for (const [rel, bytes] of baseline) expect(reshuffled.get(rel)?.equals(bytes), `byte-identical for ${rel}`).toBe(true);

    // locale-vs-byte ordering pair: "a" and "B" order differently under locale
    // collation and raw bytes — a localeCompare implementation would emit "a"
    // first; the byte comparator must emit "B" first.
    const odd = readBrandJson();
    denyOf(odd).length = 0;
    for (const entry of [
      { value: "a", reason: "byte-order probe" },
      { value: "B", reason: "byte-order probe" },
    ]) {
      denyOf(odd).push(entry);
    }
    const root = makeRoot(odd, false);
    const r = runCli(root, []);
    expect(r.status).toBe(0);
    const ts = readFileSync(path.join(root, "runtime", "shared_contracts", "brand.gen.ts"), "utf8");
    const denyIdx = ts.indexOf("TOKENS_DENY = [");
    const tail = ts.slice(denyIdx);
    const aPos = tail.indexOf('"a"');
    const bPos = tail.indexOf('"B"');
    expect(bPos).toBeGreaterThan(-1);
    expect(aPos).toBeGreaterThan(-1);
    expect(bPos, "B must sort before a in byte order").toBeLessThan(aPos);
  });

  test("TS, Python, and Rust carry identical values for the seven cross-language fields (parsed from the three emitted files)", () => {
    const { brand } = loadBrand(REPO);
    const root = makeRoot(brand, false);
    const r = runCli(root, []);
    expect(r.status).toBe(0);
    const ts = readFileSync(path.join(root, "runtime", "shared_contracts", "brand.gen.ts"), "utf8");
    const py = readFileSync(path.join(root, "runtime", "shared_contracts", "halo_agent", "brand_gen.py"), "utf8");
    const rs = readFileSync(path.join(root, "crates", "halo-brand", "src", "brand_gen.rs"), "utf8");
    for (const name of CROSS_LANG) {
      const t = parseConst(ts, name, "ts");
      const p = parseConst(py, name, "py");
      const s = parseConst(rs, name, "rs");
      expect(t, `TS value for ${name}`).not.toBe("");
      expect(p, `Python ${name} === TS`).toBe(t);
      expect(s, `Rust ${name} === TS`).toBe(t);
    }
  });

  test("a generated file that drifts is caught by --check with the path named (exit 1)", () => {
    const { brand } = loadBrand(REPO);
    const root = makeRoot(brand, true);
    const p = path.join(root, "runtime", "shared_contracts", "brand.gen.ts");
    const bytes = readFileSync(p);
    writeFileSync(p, Buffer.concat([bytes, Buffer.from("drift\n")]));
    const r = runCli(root, ["--check"]);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain("BRAND DRIFT runtime/shared_contracts/brand.gen.ts");
  });

  test("Task 2: transform rows with exact expected values (rules, not a 200-name enumeration)", () => {
    const { brand } = loadBrand(REPO);
    const b = brand as never as { env: { prefix: string; legacy_prefixes: string[] } };
    const t = (name: string): string | null => transformName(name, b.env.legacy_prefixes, b.env.prefix);
    expect(t("HERMES_KANBAN_DB")).toBe("HALO_KANBAN_DB");
    expect(t("HINDSIGHT_API_DATABASE_SCHEMA")).toBe("HALO_DATABASE_SCHEMA");
    expect(t("PI_NO_PTY")).toBe("HALO_NO_PTY");
    expect(t("OMP_HOME")).toBe("HALO_HOME");
    expect(t("NOT_A_BRAND_VAR")).toBeNull();
    // never a double swap: the result of one swap is not re-swapped
    expect(t("HALO_KANBAN_DB")).toBeNull();
  });

  test("Task 2: generated legacy tables carry identical transform values and the byte-sorted prefix order (TS + Python)", () => {
    const { brand } = loadBrand(REPO);
    const root = makeRoot(brand, true);
    const ts = readFileSync(path.join(root, "runtime", "shared_contracts", "legacyEnv.gen.ts"), "utf8");
    const py = readFileSync(path.join(root, "runtime", "shared_contracts", "halo_agent", "legacy_env_gen.py"), "utf8");
    for (const text of [ts, py]) {
      expect(text).toContain('"HERMES_KANBAN_DB": "HALO_KANBAN_DB"');
      expect(text).toContain('"HINDSIGHT_API_DATABASE_SCHEMA": "HALO_DATABASE_SCHEMA"');
      expect(text).toContain('"PI_NO_PTY": "HALO_NO_PTY"');
      expect(text).toContain('"OMP_HOME": "HALO_HOME"');
    }
    // prefix order ["HERMES_", "HINDSIGHT_API_", "OMP_", "PI_"] in both files
    for (const text of [ts, py]) {
      const iHermes = text.indexOf("HERMES_,\n  \"HINDSIGHT_API_\"");
      expect(iHermes, "prefix list must be byte-sorted").toBeGreaterThan(-1);
    }
    expect(ts).toContain('LEGACY_ENV_PREFIXES = [');
    expect(py).toContain("LEGACY_ENV_PREFIXES = (");
  });

  test("Task 2: collision refusals — two legacy names to one new name, HALO_ inside legacy_prefixes, identity name (all exit 2, output untouched)", () => {
    const cases: [string, (b: Record<string, unknown>) => void][] = [
      ["two legacy names -> one new name", (b) => {
        const env = b.env;
        if (typeof env !== "object" || env === null) throw new Error("env missing");
        (env as Record<string, unknown>).exceptions = ["HERMES_X", "PI_X"];
      }],
      ["HALO_ inside legacy_prefixes (identity at prefix level)", (b) => {
        const env = b.env;
        if (typeof env !== "object" || env === null) throw new Error("env missing");
        (env as Record<string, unknown>).legacy_prefixes = ["HERMES_", "HINDSIGHT_API_", "PI_", "OMP_", "HALO_"];
      }],
      ["a legacy name that is already a new name (identity)", (b) => {
        const env = b.env;
        if (typeof env !== "object" || env === null) throw new Error("env missing");
        (env as Record<string, unknown>).exceptions = ["HALO_FOO"];
      }],
    ];
    for (const [label, mutate] of cases) {
      const brand = readBrandJson();
      mutate(brand);
      const root = makeRoot(brand, true); // seed: valid outputs on disk
      const { brand: validBrand } = loadBrand(REPO);
      const seeded = buildOutputs(validBrand as never);
      const r = runCli(root, []);
      expect(r.status, `exit for ${label}`).toBe(2);
      expect(r.stdout, `stdout for ${label}`).toContain("COLLISION");
      for (const [rel, bytes] of seeded) {
        expect(readFileSync(path.join(root, ...rel.split("/"))).equals(bytes), `${label}: ${rel} untouched`).toBe(true);
      }
    }
  });

  test("Task 2: deny-token config — one entry per token with exact/title/upper variants, context per family", () => {
    const { brand } = loadBrand(REPO);
    const root = makeRoot(brand, true);
    const doc = JSON.parse(readFileSync(path.join(root, "tools", "rebrand", "deny-tokens.gen.json"), "utf8"));
    expect(doc.schema).toBe("halo/deny-tokens/v1");
    expect(doc.version).toBe(1);
    const tokens = (brand as never as { tokens: { deny: { value: string }[] } }).tokens.deny.map((e) => e.value).sort();
    expect(doc.entries.length).toBe(tokens.length);
    for (const entry of doc.entries) {
      const title = entry.token.charAt(0).toUpperCase() + entry.token.slice(1);
      expect(entry.case_variants).toEqual([entry.token, title, entry.token.toUpperCase()]);
      const shortFamily = ["pi_", "omp", "pi-natives"];
      const want = shortFamily.includes(entry.token) ? "identifier_string" : "all";
      expect(entry.context, `context for ${entry.token}`).toBe(want);
    }
    const byToken = new Map(doc.entries.map((e: { token: string }) => [e.token, e]));
    expect(byToken.get("oh-my-pi")?.context).toBe("all");
    expect(byToken.get("pi-natives")?.context).toBe("identifier_string");
    expect(byToken.get("pi_")?.context).toBe("identifier_string");
    expect(byToken.get("omp")?.context).toBe("identifier_string");
  });
});
